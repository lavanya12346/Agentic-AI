def get_product_price(product_name: str) -> float:
    """
    Returns the price of a product from StyleHub.
    """

    prices = {
        "shirt": 799.0,
        "jeans": 1299.0,
        "tshirt": 499.0,
        "jacket": 1999.0
    }

    return prices.get(product_name.lower(), -1.0)


print(get_product_price("shirt"))

def check_availability(product_name: str) -> bool:
    """
    Checks whether a product is available in StyleHub.
    """

    available_products = [
        "shirt",
        "jeans",
        "tshirt"
    ]

    return product_name.lower() in available_products


